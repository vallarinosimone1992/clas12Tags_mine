#!/usr/bin/env python3
"""Extract Y11 vector plot vertices, Herzkamp 2016 p.48, Fig.4.14 (PDF page 50).
No curve fitting or pixel tracing. Requires Poppler pdftocairo and Python stdlib.
"""
import argparse,csv,hashlib,json,re,subprocess,tempfile
from pathlib import Path
from xml.etree import ElementTree as ET

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--pdf',required=True,type=Path)
parser.add_argument('--output-dir',required=True,type=Path)
args=parser.parse_args()
if args.pdf.read_bytes()[:5]!=b'%PDF-':parser.error('Source must be a PDF')
with tempfile.TemporaryDirectory() as directory:
    svg=Path(directory)/'page.svg'
    subprocess.run(['pdftocairo','-f','50','-l','50','-svg',str(args.pdf),str(svg)],check=True)
    root=ET.parse(svg).getroot()
    paths=[]
    for element in root.iter():
        if element.tag.endswith('path') and element.get('stroke-dasharray'):
            # Dotted Y11, not dashed Y8; two long paths: absorption + emission.
            dash=list(map(float,element.get('stroke-dasharray').split()))
            values=re.findall(r'[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?',element.get('d',''))
            if len(values)>40 and len(dash)==2 and 1.4<dash[1]/dash[0]<1.7:
                if re.search('[CcQqAa]',element.get('d','')):raise ValueError('Expected polygonal vector curve')
                points=[tuple(map(float,values[i:i+2])) for i in range(0,len(values),2)]
                paths.append(points)
    if len(paths)!=2:raise ValueError('Expected exactly two dotted Y11 curves')
    absorption=min(paths,key=lambda p:min(y for x,y in p))
    emission=max(paths,key=lambda p:max(y for x,y in p))
    # Actual graph calibration: absorption minimum is 430 nm; its rightmost
    # endpoint is 490 nm and lies on the zero axis. Both use the same transform.
    x430,yminus=min(absorption,key=lambda p:p[1])
    x490,yzero=max(absorption,key=lambda p:p[0])
    yplus=max(y for x,y in emission)
    if not 40<yzero-yminus<50 or abs((yplus-yzero)/(yzero-yminus)-1)>.001:
        raise ValueError('Unexpected Fig.4.14 axis calibration')
    def convert(points,absorb):
        converted=[]
        for x,y in sorted(points):
            wavelength=430+(x-x430)*60/(x490-x430)
            value=(yzero-y)/(yzero-yminus) if absorb else (y-yzero)/(yplus-yzero)
            if value < -1e-5:raise ValueError('Negative spectral ordinate')
            converted.append((round(wavelength,6),max(0.,value)))
        return converted
    spectra={'absorption':convert(absorption,True),'emission':convert(emission,False)}
args.output_dir.mkdir(parents=True,exist_ok=True)
for name,data in spectra.items():
    with (args.output_dir/f'y11_{name}.csv').open('w') as stream:
        stream.write('# Herzkamp 2016 Fig.4.14, vector vertices; relative coefficient or photon intensity per nm\n')
        writer=csv.writer(stream);writer.writerow(['wavelength_nm','relative_value'])
        writer.writerows((f'{x:.6f}',f'{y:.12g}') for x,y in data)
metadata={'source_url':'https://publications.rwth-aachen.de/record/673051/files/673051.pdf',
          'download_mirror':'https://www.fz-juelich.de/++api++/de/jcns/jcns-2/downloads/dipdoc/doktorarbeit_herzkamp_pdf/@@download/file',
          'source_pdf_sha256':hashlib.sha256(args.pdf.read_bytes()).hexdigest(),
          'source':'Matthias Herzkamp, RWTH Aachen dissertation, 2016, printed pp.48-49',
          'figure':'4.14 (PDF page 50), dotted Y11 curves; Table 4.4 absolute scale',
          'normalization_k_430_ppm_inv_mm_inv':.0147,
          'calibration':{'x_430':x430,'x_490':x490,'y_zero':yzero,'y_minus_one':yminus,'y_plus_one':yplus},
          'method':'Poppler SVG vector vertices; affine axes; no fitting, smoothing or extrapolated tail',
          'emission_convention':'relative photon intensity per wavelength (per nm); assumed from plot wavelength axis',
          'limitations':['Table 4.4 caption 10cm conflicts with table 10mm; k and transmission agree with 10mm',
                         'Relative curves are representative manufacturer data; unresolved absorption outside plot support set to zero',
                         'Photon-count vs radiant-power ordinate is not explicitly specified in source; photon-count convention is an assumption']}
(args.output_dir/'provenance.json').write_text(json.dumps(metadata,indent=2)+'\n')
header='''// Generated by scripts/extract_mine_y11_spectra.py from Herzkamp 2016 Fig.4.14.
// Preserve source vertices; see experiments/mine/data/optics/y11/provenance.json.
#pragma once
#include <array>
#include <utility>
namespace mine { namespace y11data {
inline constexpr const char* version="Herzkamp2016_Fig4_14_v1";
'''
for name,data in spectra.items():
    header+=f'inline constexpr std::array<std::pair<double,double>,{len(data)}> {name} {{{{\n'
    header+=''.join(f'    {{{x:.6f}, {y:.12g}}},\n' for x,y in data)
    header+='}};\n'
header+='}} // namespace mine::y11data\n'
(args.output_dir/'mine_y11_spectral_data.h').write_text(header)
print('Extracted:',{key:len(value) for key,value in spectra.items()})
